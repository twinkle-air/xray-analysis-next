def write_registry(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=REGISTRY_FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    DESIGN.mkdir(parents=True, exist_ok=True)

    silicate_routine = build_regular(
        "silicate_oxide", "routine", FAMILIES["silicate_oxide"]["routine_count"],
        SEEDS["silicate_routine"], "D-SIL-R-", "silicate_routine")
    silicate_sparse = build_regular(
        "silicate_oxide", "sparse_boundary", FAMILIES["silicate_oxide"]["sparse_count"],
        SEEDS["silicate_sparse_boundary"], "D-SIL-S-", "silicate_sparse_boundary")
    silicate_interference, silicate_groups = build_interference(
        "silicate_oxide", FAMILIES["silicate_oxide"]["groups"],
        SEEDS["silicate_interference_bases"], "D-SIL", "silicate_interference_bases")

    iron_routine = build_regular(
        "iron_oxide", "routine", FAMILIES["iron_oxide"]["routine_count"],
        SEEDS["iron_routine"], "D-FE-R-", "iron_routine")
    iron_sparse = build_regular(
        "iron_oxide", "sparse_boundary", FAMILIES["iron_oxide"]["sparse_count"],
        SEEDS["iron_sparse_boundary"], "D-FE-S-", "iron_sparse_boundary")
    iron_interference, iron_groups = build_interference(
        "iron_oxide", FAMILIES["iron_oxide"]["groups"],
        SEEDS["iron_interference_bases"], "D-FE", "iron_interference_bases")

    candidates = (
        silicate_routine + silicate_sparse + silicate_interference
        + iron_routine + iron_sparse + iron_interference
    )

    backup_sil_routine = build_regular(
        "silicate_oxide", "routine", 5, SEEDS["backup_silicate_routine"],
        "D-BK-SIL-R-", "backup_silicate_routine")
    backup_sil_sparse = build_regular(
        "silicate_oxide", "sparse_boundary", 5, SEEDS["backup_silicate_sparse_boundary"],
        "D-BK-SIL-S-", "backup_silicate_sparse_boundary")
    backup_sil_interference, backup_sil_groups = build_interference(
        "silicate_oxide", FAMILIES["silicate_oxide"]["groups"][:1],
        SEEDS["backup_silicate_interference_bases"], "D-BK-SIL", "backup_silicate_interference_bases")
    backup_fe_routine = build_regular(
        "iron_oxide", "routine", 5, SEEDS["backup_iron_routine"],
        "D-BK-FE-R-", "backup_iron_routine")
    backup_fe_sparse = build_regular(
        "iron_oxide", "sparse_boundary", 5, SEEDS["backup_iron_sparse_boundary"],
        "D-BK-FE-S-", "backup_iron_sparse_boundary")
    backup_fe_interference, backup_fe_groups = build_interference(
        "iron_oxide", FAMILIES["iron_oxide"]["groups"][:1],
        SEEDS["backup_iron_interference_bases"], "D-BK-FE", "backup_iron_interference_bases")
    backups = (
        backup_sil_routine + backup_sil_sparse + backup_sil_interference
        + backup_fe_routine + backup_fe_sparse + backup_fe_interference
    )

    # Shards: round-robin routine/sparse within the family, one complete group per shard.
    shards: dict[str, list[dict]] = {f"S{i:02d}": [] for i in range(1, 11)}
    for index, sample in enumerate(silicate_routine, 1):
        shards[f"S{(index - 1) % 6 + 1:02d}"].append(sample)
    for index, sample in enumerate(silicate_sparse, 1):
        shards[f"S{(index - 1) % 6 + 1:02d}"].append(sample)
    for group_index, group in enumerate(silicate_groups, 1):
        shards[f"S{group_index:02d}"].extend(
            [sample for sample in silicate_interference
             if sample["provenance"]["d_design"]["group_id"] == group["group_id"]])
    for index, sample in enumerate(iron_routine, 1):
        shards[f"S{7 + (index - 1) % 4:02d}"].append(sample)
    for index, sample in enumerate(iron_sparse, 1):
        shards[f"S{7 + (index - 1) % 4:02d}"].append(sample)
    for group_index, group in enumerate(iron_groups, 1):
        shards[f"S{6 + group_index:02d}"].extend(
            [sample for sample in iron_interference
             if sample["provenance"]["d_design"]["group_id"] == group["group_id"]])

    shard_of: dict[str, str] = {}
    for shard_id, samples in shards.items():
        for sample in samples:
            if sample["id"] in shard_of:
                raise ValueError("Sample assigned to two shards: " + sample["id"])
            shard_of[sample["id"]] = shard_id

    # Write shards.
    for shard_id, samples in shards.items():
        dump_json(DESIGN / "shards" / f"{shard_id}.json", {"samples": samples})

    # Registry and samples.
    registry_rows = [registry_row(sample, shard_of.get(sample["id"])) for sample in candidates]
    backup_rows = [registry_row(sample, None) for sample in backups]
    write_registry(DESIGN / "formula_registry_D.csv", registry_rows)
    write_registry(DESIGN / "backup_registry_D.csv", backup_rows)

    counts = {
        "silicate_oxide": {
            "routine": len(silicate_routine),
            "sparse_boundary": len(silicate_sparse),
            "interference": len(silicate_interference),
            "total": len(silicate_routine) + len(silicate_sparse) + len(silicate_interference),
        },
        "iron_oxide": {
            "routine": len(iron_routine),
            "sparse_boundary": len(iron_sparse),
            "interference": len(iron_interference),
            "total": len(iron_routine) + len(iron_sparse) + len(iron_interference),
        },
        "total": len(candidates),
        "backups": len(backups),
    }

    dump_json(DESIGN / "candidate_samples_D.json", {
        "schema": "D-candidate-samples/v1",
        "owner": "D",
        "round_id": SEED_MANIFEST["round_id"],
        "status": "provisional_pending_A_dedup",
        "counts": counts,
        "design_ranges_sha256": sha256_file(FROZEN / "design_ranges.json"),
        "seed_manifest_sha256": sha256_file(ROOT / "D_seed_manifest.json"),
        "samples": candidates,
    })
    dump_json(DESIGN / "backup_samples_D.json", {
        "schema": "D-candidate-samples/v1",
        "owner": "D",
        "status": "backup_pending_A_use",
        "counts": {"total": len(backups)},
        "samples": backups,
    })

    dump_json(DESIGN / "parent_families_D.json", {
        "schema": "D-parent-families/v1",
        "groups": silicate_groups + iron_groups
        + backup_sil_groups + backup_fe_groups,
    })

    # Coverage.
    coverage = {}
    coverage_checks = {}
    for family in ("silicate_oxide", "iron_oxide"):
        coverage[family] = {}
        for stratum in ("routine", "sparse_boundary", "interference"):
            samples = [s for s in candidates
                       if s["provenance"]["d_design"]["family"] == family
                       and s["provenance"]["d_design"]["stratum"] == stratum]
            block = coverage_block(samples, spec_for(family, stratum), stratum)
            coverage[family][stratum] = block
            coverage_checks[f"{family}/{stratum}"] = block["checks"]
    dump_json(DESIGN / "coverage_D.json", {
        "schema": "D-coverage/v1",
        "description": "Routine/sparse traces are gated on log10 span and nonzero fraction; compounds and balances on linear span. Interference groups are controlled families and are not gated on population span or nonzero fraction.",
        "coverage": coverage,
        "checks": coverage_checks,
    })

    # Vector file for cross-member dedup.
    vectors = []
    for sample in candidates:
        vector = canonical_vector(sample)
        design = sample["provenance"]["d_design"]
        vectors.append({
            "id": sample["id"],
            "family": design["family"],
            "stratum": design["stratum"],
            "group_id": design.get("group_id"),
            "vector": vector,
            "sha256": vector_sha(vector),
        })
    dump_json(DESIGN / "candidate_vectors_D.json", {
        "schema": "D-candidate-vectors/v1",
        "target_order": TARGETS,
        "count": len(vectors),
        "vectors": vectors,
    })

    # Checks.
    errors: list[str] = []
    warnings: list[str] = []

    if len(candidates) != 250:
        errors.append(f"Candidate count {len(candidates)} != 250")
    if counts["silicate_oxide"] != {"routine": 90, "sparse_boundary": 30,
                                    "interference": 30, "total": 150}:
        errors.append("Silicate counts do not match quota")
    if counts["iron_oxide"] != {"routine": 60, "sparse_boundary": 20,
                                 "interference": 20, "total": 100}:
        errors.append("Iron counts do not match quota")
    if len(backups) != 30:
        errors.append(f"Backup count {len(backups)} != 30")

    ids = [sample["id"] for sample in candidates]
    backup_ids = [sample["id"] for sample in backups]
    if len(ids) != len(set(ids)):
        errors.append("Duplicate candidate IDs")
    if len(backup_ids) != len(set(backup_ids)):
        errors.append("Duplicate backup IDs")
    if set(ids) & set(backup_ids):
        errors.append("Backup ID collides with candidate ID")

    closure_deviations = []
    recompute_deviations = []
    range_violations = []
    for sample in candidates + backups:
        design = sample["provenance"]["d_design"]
        spec = spec_for(design["family"], design["stratum"])
        compounds = sample["provenance"]["compounds_percent"]
        traces = sample["provenance"]["trace_ppm"]
        total = sum(float(v) for v in sample["composition_percent"].values())
        closure_deviations.append(abs(total - 100.0))
        recomputed, _ = components_to_elements(compounds, traces, closure="strict")
        element_keys = set(recomputed) | set(sample["composition_percent"])
        recompute_deviations.append(max(
            abs(float(recomputed.get(k, 0.0)) - float(sample["composition_percent"].get(k, 0.0)))
            for k in element_keys))
        for name, (lo, hi) in spec["compound_ranges_percent"].items():
            if not in_range(float(compounds[name]), lo, hi):
                range_violations.append(f"{sample['id']}: compound {name}={compounds[name]}")
        balance = spec["balance_compound"]
        if not in_range(float(compounds[balance]), *spec["balance_range_percent"]):
            range_violations.append(f"{sample['id']}: balance {balance}={compounds[balance]}")
        for name, (lo, hi) in spec["trace_ranges_ppm"].items():
            value = float(traces[name])
            if value != 0.0 and not in_range(value, lo, hi):
                range_violations.append(f"{sample['id']}: trace {name}={value}")

    max_closure = max(closure_deviations)
    max_recompute = max(recompute_deviations)
    if max_closure > 1e-9:
        errors.append(f"Closure deviation {max_closure} > 1e-9")
    if max_recompute > 1e-9:
        errors.append(f"Recompute deviation {max_recompute} > 1e-9")
    if range_violations:
        errors.extend(range_violations[:20])
        if len(range_violations) > 20:
            errors.append(f"... {len(range_violations) - 20} more range violations")

    # Exact duplicate vectors.
    vector_by_id = {entry["id"]: entry for entry in vectors}
    by_sha: dict[str, list[str]] = {}
    for entry in vectors:
        by_sha.setdefault(entry["sha256"], []).append(entry["id"])
    duplicate_groups = [members for members in by_sha.values() if len(members) > 1]
    if duplicate_groups:
        errors.append(f"Duplicate composition vectors: {duplicate_groups}")

    # Near-duplicate report on range-normalised target vectors.
    observed_max = [max(entry["vector"][i] for entry in vectors) for i in range(len(TARGETS))]
    scale = [max(value, 1e-12) for value in observed_max]
    group_of = {entry["id"]: entry["group_id"] for entry in vectors}
    near_pairs = []
    min_non_group = None
    for i in range(len(vectors)):
        left = vectors[i]
        for j in range(i + 1, len(vectors)):
            right = vectors[j]
            same_group = bool(left["group_id"]) and left["group_id"] == right["group_id"]
            distance = math.sqrt(sum(
                ((left["vector"][k] - right["vector"][k]) / scale[k]) ** 2
                for k in range(len(TARGETS))))
            if not same_group:
                if min_non_group is None or distance < min_non_group:
                    min_non_group = distance
                if distance < 0.01:
                    near_pairs.append({
                        "left": left["id"], "right": right["id"], "distance": distance,
                    })
    near_pairs.sort(key=lambda item: item["distance"])
    if near_pairs:
        warnings.append(f"{len(near_pairs)} non-group pairs below normalised distance 0.01")

    # Shard checks.
    shard_checks = {}
    for shard_id, samples in shards.items():
        family = "silicate_oxide" if shard_id <= "S06" else "iron_oxide"
        stratum_counts = Counter(s["provenance"]["d_design"]["stratum"] for s in samples)
        group_ids = sorted({s["provenance"]["d_design"]["group_id"]
                            for s in samples if s["provenance"]["d_design"]["group_id"]})
        variants = sorted(s["provenance"]["d_design"]["variant"]
                          for s in samples if s["provenance"]["d_design"]["variant"])
        families = {s["provenance"]["d_design"]["family"] for s in samples}
        checks = {
            "count_25": len(samples) == 25,
            "routine_15": stratum_counts.get("routine", 0) == 15,
            "sparse_5": stratum_counts.get("sparse_boundary", 0) == 5,
            "interference_5": stratum_counts.get("interference", 0) == 5,
            "family_pure": families == {family},
            "one_group": len(group_ids) == 1,
            "variants_v0_v4": variants == ["V0", "V1", "V2", "V3", "V4"],
        }
        shard_checks[shard_id] = {"checks": checks, "counts": dict(stratum_counts),
                                  "group_ids": group_ids}
        if not all(checks.values()):
            errors.append(f"Shard {shard_id} failed: {checks}")

    # Group checks.
    group_checks = {}
    all_groups = silicate_groups + iron_groups
    for info in all_groups:
        group_id = info["group_id"]
        group_samples = [s for s in candidates
                         if s["provenance"]["d_design"]["group_id"] == group_id]
        pair = info["pair"]
        balance = info["balance_compound"]
        expected = info["levels_ppm"]
        checks = {"count_5": len(group_samples) == 5, "pair_levels": True,
                  "shared_non_pair": True, "parent_ids": True, "balanced": True}
        reference = None
        for sample in group_samples:
            design = sample["provenance"]["d_design"]
            index = int(design["variant"][1:])
            levels = design["pair_level_ppm"]
            if abs(float(levels[pair[0]]) - expected[index][pair[0]]) > 1e-9 or \
               abs(float(levels[pair[1]]) - expected[index][pair[1]]) > 1e-9:
                checks["pair_levels"] = False
            if design["parent_id"] != f"{group_id}-V0":
                checks["parent_ids"] = False
            compounds = sample["provenance"]["compounds_percent"]
            traces = sample["provenance"]["trace_ppm"]
            signature = (
                tuple(sorted((k, float(v)) for k, v in compounds.items() if k != balance)),
                tuple(sorted((k, float(v)) for k, v in traces.items() if k not in pair)),
            )
            if reference is None:
                reference = signature
            elif signature != reference:
                checks["shared_non_pair"] = False
            rest = 100.0 - sum(float(v) for k, v in compounds.items() if k != balance) \
                - sum(float(v) for v in traces.values()) / 10000.0
            if abs(float(compounds[balance]) - rest) > 1e-9:
                checks["balanced"] = False
        group_checks[group_id] = {"checks": checks, "pair": pair,
                                  "common_level_ppm": info["common_level_ppm"]}
        if not all(checks.values()):
            errors.append(f"Group {group_id} failed: {checks}")

    # Coverage hard checks.
    for key, checks in coverage_checks.items():
        if not checks.get("range_ok", False):
            errors.append(f"Coverage range violation in {key}: {checks.get('range_violations')}")
        if not checks.get("nonzero_ok", True):
            errors.append(f"Low trace nonzero coverage in {key}: {checks.get('low_nonzero')}")
        if not checks.get("span_ok", True):
            detail = checks.get("low_span") or checks.get("low_log_span")
            errors.append(f"Low span coverage in {key}: {detail}")

    # Backup range/closure is covered above; check exact duplicate vs candidates.
    backup_sha = {vector_sha(canonical_vector(sample)) for sample in backups}
    if backup_sha & set(by_sha):
        errors.append("Backup composition duplicates a candidate")

    status = "selfcheck_passed" if not errors else "selfcheck_failed"
    acceptance = ("coordinator_direct_confirmation_no_A_dedup" if not errors
                  else "blocked_selfcheck_failed")
    checks_report = {
        "schema": "D-design-checks/v1",
        "owner": "D",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": status,
        "acceptance": acceptance,
        "acceptance_note": ("Coordinator confirmed the candidate set on 2026-10-22 and waived "
                            "the A cross-member dedup response before spectra generation."
                            if not errors else "Self-check must pass before any acceptance."),
        "cross_member_dedup": "waived_by_coordinator" if not errors else "not_applicable",
        "counts": counts,
        "hard_checks": {
            "candidate_count_250": len(candidates) == 250,
            "quota_match": not any("counts do not match" in e for e in errors),
            "id_unique": len(ids) == len(set(ids)),
            "vector_unique": not duplicate_groups,
            "closure_ok": max_closure <= 1e-9,
            "recompute_ok": max_recompute <= 1e-9,
            "range_ok": not range_violations,
            "shards_ok": all(all(v["checks"].values()) for v in shard_checks.values()),
            "groups_ok": all(all(v["checks"].values()) for v in group_checks.values()),
            "coverage_ok": all(
                c.get("range_ok", False) and c.get("nonzero_ok", True) and c.get("span_ok", True)
                for c in coverage_checks.values()),
            "backup_ok": len(backups) == 30 and not (backup_sha & set(by_sha)),
        },
        "max_closure_deviation_percent": max_closure,
        "max_recompute_deviation_percent": max_recompute,
        "range_violation_count": len(range_violations),
        "duplicate_groups": duplicate_groups,
        "dedup": {
            "exact_duplicate_groups": len(duplicate_groups),
            "min_non_group_normalised_distance": min_non_group,
            "near_pair_count_below_0_01": len(near_pairs),
            "nearest_pairs": near_pairs[:50],
        },
        "shards": shard_checks,
        "groups": group_checks,
        "coverage": coverage_checks,
        "errors": errors,
        "warnings": warnings,
    }
    dump_json(DESIGN / "design_checks_D.json", checks_report)

    dump_json(DESIGN / "D_design_scope.json", {
        "owner": "D",
        "status": "coordinator_confirmed_no_A_dedup" if not errors else "provisional_pending_fix",
        "scope_note": ("A freeze manifest is A-only; D does not claim a global freeze. "
                       "The coordinator confirmed the D candidate set on 2026-10-22 and waived "
                       "the A cross-member dedup response before spectra generation."),
        "cross_member_dedup": "waived_by_coordinator" if not errors else "not_applicable",
        "frozen_inputs": {
            name: sha256_file(FROZEN / name)
            for name in ("P1.json", "P2.json", "P3.json", "design_ranges.json", "A_run_config.json")
        },
        "candidate_count": len(candidates),
        "backup_count": len(backups),
        "no_spectra_generated": True,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
    })

    print(json.dumps({
        "status": status,
        "counts": counts,
        "max_closure_deviation_percent": max_closure,
        "max_recompute_deviation_percent": max_recompute,
        "range_violations": len(range_violations),
        "duplicate_groups": len(duplicate_groups),
        "near_pairs": len(near_pairs),
        "min_non_group_distance": min_non_group,
        "shards": {sid: v["checks"] for sid, v in shard_checks.items()},
        "errors": errors[:10],
        "warnings": warnings,
        "outputs": str(DESIGN),
    }, ensure_ascii=False, indent=2))
    return 0 if not errors else 1


