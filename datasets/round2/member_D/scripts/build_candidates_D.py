def json_default(value):
    if hasattr(value, "item"):
        return value.item()
    raise TypeError(f"Not JSON serializable: {type(value)!r}")


def dump_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, default=json_default) + "\n",
        encoding="utf-8",
    )


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def in_range(value: float, lo: float, hi: float, tol: float = 1e-9) -> bool:
    return lo - tol <= value <= hi + tol


def geometric_mean(lo: float, hi: float) -> float:
    return math.sqrt(lo * hi)


def canonical_vector(sample: dict) -> list[float]:
    elements = sample["composition_percent"]
    values = [float(elements.get(symbol, 0.0)) for symbol in TARGETS]
    total = sum(values)
    if total <= 0:
        raise ValueError("Target elements sum to zero for " + sample["id"])
    return [round(value / total * 100.0, 12) for value in values]


def vector_sha(vector: list[float]) -> str:
    payload = json.dumps(vector, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def add_regular(raw: dict, sample_id: str, family: str, stratum: str, call_id: str,
                seed: int, section: str) -> dict:
    sample = deepcopy(raw)
    sample["id"] = sample_id
    sample["provenance"]["d_design"] = {
        "design_version": "D-candidate-v1",
        "family": family,
        "stratum": stratum,
        "design_section": section,
        "design_call": call_id,
        "design_seed": seed,
        "designer_id": raw["id"],
        "group_id": None,
        "variant": None,
        "parent_id": None,
        "pair": None,
        "pair_level_ppm": None,
    }
    return sample


def build_regular(family: str, stratum: str, count: int, seed: int, prefix: str,
                  call_id: str) -> list[dict]:
    result = design_minerals(RANGES[family][stratum], count, seed)
    return [
        add_regular(raw, f"{prefix}{index:03d}", family, stratum, call_id, seed, stratum)
        for index, raw in enumerate(result["samples"], 1)
    ]


def build_interference_group(raw_base: dict, group_id: str, pair: tuple[str, str],
                             spec: dict, call_id: str, seed: int,
                             family: str) -> tuple[list[dict], dict]:
    pair_a, pair_b = pair
    balance = spec["balance_compound"]
    base_compounds = raw_base["provenance"]["compounds_percent"]
    base_traces = raw_base["provenance"]["trace_ppm"]
    non_balance = {key: value for key, value in base_compounds.items() if key != balance}
    non_pair = {key: value for key, value in base_traces.items() if key not in pair}

    lo_a, hi_a = spec["trace_ranges_ppm"][pair_a]
    lo_b, hi_b = spec["trace_ranges_ppm"][pair_b]
    level_a = geometric_mean(lo_a, hi_a)
    level_b = geometric_mean(lo_b, hi_b)
    common = min(math.sqrt(level_a * level_b), hi_a / 5.0, hi_b)
    if common < max(lo_a, lo_b, 1e-12):
        raise ValueError(f"Interference level infeasible for {group_id}: {common}")
    levels = [(0.0, 0.0), (common, 0.0), (0.0, common),
              (common, common), (5.0 * common, common)]

    balance_lo, balance_hi = spec["balance_range_percent"]
    variants: list[dict] = []
    for variant_index, (value_a, value_b) in enumerate(levels):
        if value_a > hi_a + 1e-9 or value_b > hi_b + 1e-9:
            raise ValueError(f"Level outside range for {group_id} V{variant_index}")
        traces = dict(non_pair)
        traces[pair_a] = value_a
        traces[pair_b] = value_b
        rest = 100.0 - sum(non_balance.values()) - sum(traces.values()) / 10000.0
        if not in_range(rest, balance_lo, balance_hi):
            raise ValueError(
                f"Balance {rest} outside [{balance_lo},{balance_hi}] for {group_id} V{variant_index}")
        compounds = dict(non_balance)
        compounds[balance] = rest
        used, provenance = components_to_elements(compounds, traces, closure="strict")
        sample_id = f"{group_id}-V{variant_index}"
        provenance["d_design"] = {
            "design_version": "D-candidate-v1",
            "family": family,
            "stratum": "interference",
            "design_section": "interference",
            "design_call": call_id,
            "design_seed": seed,
            "designer_id": raw_base["id"],
            "group_id": group_id,
            "variant": f"V{variant_index}",
            "parent_id": f"{group_id}-V0",
            "pair": [pair_a, pair_b],
            "pair_level_ppm": {pair_a: value_a, pair_b: value_b},
            "pair_level_common_ppm": common,
            "base_designer_trace_ppm": base_traces,
            "notes": [
                "Base matrix from sealed designer; only the controlled trace pair and balance vary.",
                "V0=0/0, V1=L/0, V2=0/L, V3=L/L, V4=5L/L; L is a common ppm level within both ranges.",
            ],
        }
        variants.append({
            "id": sample_id,
            "composition_percent": used,
            "provenance": provenance,
        })

    group_info = {
        "group_id": group_id,
        "family": family,
        "pair": [pair_a, pair_b],
        "common_level_ppm": common,
        "levels_ppm": [
            {pair_a: value_a, pair_b: value_b} for value_a, value_b in levels
        ],
        "base_id": f"{group_id}-V0",
        "base_designer_id": raw_base["id"],
        "base_designer_compounds_percent": base_compounds,
        "base_designer_trace_ppm": base_traces,
        "balance_compound": balance,
        "shared_fields": sorted(non_balance) + sorted(non_pair),
        "varying_fields": [pair_a, pair_b, balance],
    }
    return variants, group_info


def build_interference(family: str, groups: list[tuple[str, str]], seed: int,
                       id_prefix: str, call_id: str) -> tuple[list[dict], list[dict]]:
    count = len(groups)
    result = design_minerals(RANGES[family]["interference"], count, seed)
    samples: list[dict] = []
    group_infos: list[dict] = []
    for index, (raw_base, pair) in enumerate(zip(result["samples"], groups), 1):
        group_id = f"{id_prefix}-I-{index:02d}"
        variants, info = build_interference_group(
            raw_base, group_id, pair, RANGES[family]["interference"], call_id, seed, family)
        samples.extend(variants)
        group_infos.append(info)
    return samples, group_infos


def spec_for(family: str, stratum: str) -> dict:
    return RANGES[family][stratum]


def range_variables(spec: dict) -> list[tuple[str, str, float, float]]:
    variables: list[tuple[str, str, float, float]] = []
    for name, (lo, hi) in spec["compound_ranges_percent"].items():
        variables.append((name, "compound", lo, hi))
    balance = spec["balance_compound"]
    lo, hi = spec["balance_range_percent"]
    variables.append((balance, "balance", lo, hi))
    for name, (lo, hi) in spec["trace_ranges_ppm"].items():
        variables.append((name, "trace", lo, hi))
    return variables


def value_for(sample: dict, name: str, kind: str) -> float:
    provenance = sample["provenance"]
    if kind == "trace":
        return float(provenance["trace_ppm"].get(name, 0.0))
    return float(provenance["compounds_percent"].get(name, 0.0))


def quantile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    position = (len(ordered) - 1) * q
    lower = int(math.floor(position))
    upper = int(math.ceil(position))
    if lower == upper:
        return ordered[lower]
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower)


def coverage_block(samples: list[dict], spec: dict, stratum: str) -> dict:
    population_gate = stratum != "interference"
    block: dict = {"n": len(samples), "population_gate": population_gate,
                   "variables": {}, "checks": {}}
    for name, kind, lo, hi in range_variables(spec):
        values = [value_for(sample, name, kind) for sample in samples]
        minimum, maximum = min(values), max(values)
        span = (maximum - minimum) / (hi - lo) if hi > lo else 0.0
        nonzero = sum(value > 0 for value in values) / len(values)
        positive = [value for value in values if value > 0]
        log_span = None
        if kind == "trace" and len(positive) > 1 and lo > 0:
            log_span = ((math.log10(max(positive)) - math.log10(min(positive)))
                        / math.log10(hi / lo))
        range_ok = all(
            (value == 0.0 if kind == "trace" else False) or in_range(value, lo, hi)
            for value in values
        )
        item = {
            "kind": kind,
            "declared_range": [lo, hi],
            "observed_min": minimum,
            "observed_max": maximum,
            "positive_min": min(positive) if positive else None,
            "positive_max": max(positive) if positive else None,
            "positive_count": len(positive),
            "median": quantile(values, 0.5),
            "q1": quantile(values, 0.25),
            "q3": quantile(values, 0.75),
            "span_fraction": span,
            "log_span_fraction": log_span,
            "nonzero_fraction": nonzero,
            "range_ok": range_ok,
        }
        block["variables"][name] = item
        if not range_ok:
            block["checks"].setdefault("range_violations", []).append(name)
        if population_gate:
            if kind == "trace":
                if nonzero < 0.5:
                    block["checks"].setdefault("low_nonzero", []).append(name)
                if log_span is None or log_span < 0.5:
                    block["checks"].setdefault("low_log_span", []).append(name)
            elif span < 0.5:
                block["checks"].setdefault("low_span", []).append(name)
    block["checks"]["range_ok"] = "range_violations" not in block["checks"]
    block["checks"]["nonzero_ok"] = (not population_gate) or ("low_nonzero" not in block["checks"])
    block["checks"]["span_ok"] = (not population_gate) or (
        "low_span" not in block["checks"] and "low_log_span" not in block["checks"])
    block["checks"]["span_metric"] = (
        "not_applicable_controlled_family" if not population_gate
        else "log10_for_traces_linear_for_compounds")
    return block


def registry_row(sample: dict, shard: str | None) -> dict:
    provenance = sample["provenance"]
    design = provenance["d_design"]
    compounds = provenance["compounds_percent"]
    traces = provenance["trace_ppm"]
    balance = spec_for(design["family"], design["stratum"])["balance_compound"]
    vector = canonical_vector(sample)
    pair = design.get("pair") or [None, None]
    levels = design.get("pair_level_ppm") or {}
    return {
        "sample_id": sample["id"],
        "family": design["family"],
        "stratum": design["stratum"],
        "shard": shard or "",
        "group_id": design.get("group_id") or "",
        "variant": design.get("variant") or "",
        "parent_id": design.get("parent_id") or "",
        "pair_a": pair[0] or "",
        "pair_b": pair[1] or "",
        "level_a_ppm": levels.get(pair[0], "") if pair[0] else "",
        "level_b_ppm": levels.get(pair[1], "") if pair[1] else "",
        "balance_compound": balance,
        "balance_percent": compounds.get(balance, ""),
        "compound_sum_percent": sum(float(v) for v in compounds.values()),
        "trace_sum_ppm": sum(float(v) for v in traces.values()),
        "element_sum_percent": sum(float(v) for v in sample["composition_percent"].values()),
        "composition_sha256": vector_sha(vector),
        "design_call": design["design_call"],
        "design_seed": design["design_seed"],
        "designer_id": design["designer_id"],
        "compounds_percent_json": json.dumps(compounds, ensure_ascii=False, sort_keys=True,
                                             default=json_default),
        "trace_ppm_json": json.dumps(traces, ensure_ascii=False, sort_keys=True,
                                     default=json_default),
        "notes": "strict closure; Fe2O3T reported as Fe2O3 convention",
    }


